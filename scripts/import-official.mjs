// Reads every published PF2e troop actor from a local PF2e system source checkout and emits stat
// cards through `cardFromActor`, the reading a Foundry client makes of the same actor.
// Usage: PF2E_SOURCE=/path/to/pf2e/packs/pf2e node scripts/import-official.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createServer } from 'vite';
import { officialTroops } from './troop-signals.mjs';

const root = process.env.PF2E_SOURCE ?? join(import.meta.dirname, '../../pf2e-reignmaker/_pf2e-source/packs/pf2e');

// Vite resolves the adapter's `.js` specifiers to their `.ts` files, which plain Node does not.
const vite = await createServer({ configFile: false, server: { middlewareMode: true }, appType: 'custom', logLevel: 'error', optimizeDeps: { noDiscovery: true } });
const { cardFromActor } = await vite.ssrLoadModule('/src/adapters/pf2e/troopCard.ts');
await vite.close();

// Six ReignMaker armies are published troops under the same name; the ReignMaker card stands.
const troopsDir = new URL('../data/troops/', import.meta.url);
const reignmaker = new Set(readdirSync(troopsDir).filter((f) => f.endsWith('.json'))
  .map((f) => JSON.parse(readFileSync(new URL(f, troopsDir), 'utf8')).name));

const cards = officialTroops(root).filter(([, d]) => !reignmaker.has(d.name))
  .map(([, d]) => ({ ...cardFromActor(d), source: d.system.details.publication?.title ?? '' }))
  .sort((a, b) => a.level - b.level || a.name.localeCompare(b.name));

const body = cards.map((c) => {
  const o = c.overrides;
  const reach = o.reach ? `'${o.reach}'` : 'null';
  return `  { name: ${JSON.stringify(c.name)}, level: ${c.level}, role: '${c.role}', salvo: ${reach}, pace: ${c.pace}, fear: ${c.fear}, caster: ${c.caster}, ${c.tradition ? `tradition: '${c.tradition}', ` : ''}signals: ${JSON.stringify(c.signals)}, tactics: [], sheet: ${JSON.stringify(c.sheet)}, overrides: { strike: ${o.strike}, volley: ${o.volley}, reach: ${reach}, defence: ${o.defence}, will: ${o.will}, perception: ${o.perception} } }, // ${c.source}`;
}).join('\n');

writeFileSync(new URL('../src/engine/official.ts', import.meta.url),
`import type { UnitCard } from './cards.js';

// Generated by scripts/import-official.mjs from the Pathfinder Second Edition system source (ORC licence). Numbers only.
export const OFFICIAL: UnitCard[] = [
${body}
];
`);
console.log(`${cards.length} official troops written`);
